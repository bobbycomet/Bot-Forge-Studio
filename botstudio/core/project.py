@dataclass
class BuildResult:
    files: dict = field(default_factory=dict)        # relative path -> text
    cogs: list = field(default_factory=list)         # CogSource
    warnings: list = field(default_factory=list)
    errors: list = field(default_factory=list)
    intents: set = field(default_factory=set)
    requirements: list = field(default_factory=list)
    env: dict = field(default_factory=dict)          # NAME -> (default, comment)
    manifest: dict = field(default_factory=dict)
    entry: str = "bot.py"
    dashboard: bool = False                          # the build includes the discord.js web dashboard (dashboard/)

    @property
    def ok(self) -> bool:
        return not self.errors


def _h(text: str) -> str:
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:16]


def build(graph: Graph) -> BuildResult:
    res = BuildResult()
    s = graph.settings
    used: set[str] = set()
    cogs: list[CogSource] = []

    comps = graph.components()
    # components that contain web-only nodes (Web Dashboard, Web Route …) compile into the dashboard, not the bot
    web_comps = [c for c in comps if any(n.spec is not None and n.spec.web_only for n in c)]
    for comp in (c for c in comps if c not in web_comps):
        try:
            cog = compile_component(graph, comp, used)
        except GenError as e:
            res.errors.append(str(e))
            continue
        if cog is None:
            continue
        res.warnings += cog.warnings
        if cog.path or cog.extra_files:
            cogs.append(cog)

    if not cogs and not res.errors:
        res.warnings.append("The graph is empty — add a trigger (e.g. Slash Command) to get started.")

    # syntax-check every generated file so errors show up in the editor, not at 3am on the server
    for cog in cogs:
        for path, src in [(cog.path, cog.source)] + list(cog.extra_files.items()):
            if path.endswith(".py"):
                try:
                    compile(src, path, "exec")
                except SyntaxError as e:
                    res.errors.append(f"{path}:{e.lineno}: {e.msg}")

    intents, reqs = set(s.extra_intents), set(BASE_REQUIREMENTS) | set(s.extra_requirements)
    for cog in cogs:
        intents |= cog.intents
        reqs |= cog.requires
        for name, default, comment in cog.env:
            res.env.setdefault(name, (default, comment))
    res.intents, res.cogs = intents, cogs
    res.requirements = sorted(reqs, key=str.lower)

    standalone = [n for n in graph.nodes.values() if n.spec and n.spec.standalone]
    if standalone:
        if web_comps:
            res.warnings.append("A standalone bot module runs as its own process — the web dashboard was not generated.")
        return _build_standalone(graph, res, standalone[0], cogs, reqs)
    dash_files: dict[str, str] = {}
    if web_comps:
        from .project_web import build_dashboard     # lazy: it imports BuildResult-free helpers only
        dash_files = build_dashboard(graph, web_comps, res, used)
        res.dashboard = bool(dash_files)

    lines = []
    for name in sorted(intents):
        if name in INTENT_NAMES:
            lines.append(f"intents.{name} = True")
    bot_py = BOT_PY
    for key, val in {
        "VERSION": __version__, "NAME": s.name.replace("\n", " "),
        "TOKEN_ENV": repr(s.token_env), "LOG_LEVEL": repr(s.log_level),
        "INTENTS": "\n".join(lines) or "# (default intents only)",
        "STATUS_TEXT": repr(s.status_text), "ACTIVITY": repr(s.activity_type),
        "HOT_RELOAD": repr(bool(s.hot_reload)), "PREFIX": repr(s.command_prefix or "!"),
    }.items():
        bot_py = bot_py.replace(f"@@{key}@@", val)

    files = {
        "bot.py": bot_py,
        "bs_runtime.py": RUNTIME_SRC.read_text(encoding="utf-8"),
        "cogs/__init__.py": "",
        "requirements.txt": "\n".join(res.requirements) + "\n",
    }
    for cog in cogs:
        files[cog.path] = cog.source
        files.update(cog.extra_files)
    files.update(dash_files)

    env_lines = [f"# {s.name} — copy to .env and fill in", f"{s.token_env}=",
                 f"GUILD_ID={s.dev_guild_id}  # optional: instant command sync for one test server",
                 f"LOG_LEVEL={s.log_level}"]
    for name, (default, comment) in sorted(res.env.items()):
        env_lines.append(f"# {comment}" if comment else "")
        env_lines.append(f"{name}={default}")
    files[".env.example"] = "\n".join(x for x in env_lines if x is not None) + "\n"

    cog_hashes = {c.path: _h(files[c.path]) for c in cogs}
    cmd_cogs = [f"{c.path}:{cog_hashes[c.path]}" for c in cogs if c.commands]
    restart_files = {p: _h(t) for p, t in files.items()
                     if p not in cog_hashes and p != ".env.example" and p != "cogs/__init__.py"
                     and not p.startswith("dashboard/")}      # the bot supervises the dashboard separately
    manifest = {
        "bot": s.slug,
        "studio": __version__,
        "cogs": cog_hashes,
        "commands_sig": _h("|".join(sorted(cmd_cogs))),
        "restart_sig": _h(json.dumps(restart_files, sort_keys=True)),
        "files": {p: _h(t) for p, t in files.items()},
    }
    if res.dashboard:
        # the bot restarts the dashboard process only when these change; config.json, routes/ and web/public/ reload live
        manifest["dashboard"] = True
        manifest["dashboard_sig"] = _h(json.dumps({p: _h(files[p]) for p in
                                                   ("dashboard/server.js", "dashboard/bs_dash.js", "dashboard/package.json")},
                                                  sort_keys=True))
    files["manifest.json"] = json.dumps(manifest, indent=2)
    res.files, res.manifest = files, manifest
    return res


def _build_standalone(graph: Graph, res: BuildResult, node, cogs, reqs) -> BuildResult:
    """A wrapped, complete bot (a script-style bot with its own client): ship its files verbatim; the service runs its entry script."""
    s = graph.settings
    others = [n for n in graph.nodes.values() if n is not node]
    if others:
        res.warnings.append("A standalone bot module runs as its own process — the other nodes were ignored.")
    files: dict = {}
    for c in cogs:
        files.update(c.extra_files)
    reqs = sorted(set(reqs) - {"discord.py>=2.5", "python-dotenv>=1.0"} | {"discord.py>=2.5", "python-dotenv>=1.0"},
                  key=str.lower)
    if "requirements.txt" not in files:
        files["requirements.txt"] = "\n".join(reqs) + "\n"
    env = [f"# {s.name}", f"{s.token_env}="]
    for c in cogs:
        for name, default, comment in c.env:
            env += [f"# {comment}" if comment else "", f"{name}={default}"]
    files[".env.example"] = "\n".join(env) + "\n"
    entry = node.spec.standalone
    hashes = {p: _h(t) for p, t in files.items() if p != ".env.example"}
    res.manifest = {"bot": s.slug, "studio": __version__, "cogs": {}, "commands_sig": "", "entry": entry,
                    "restart_sig": _h(json.dumps(hashes, sort_keys=True)),
                    "files": {p: _h(t) for p, t in files.items()}}
    files["manifest.json"] = json.dumps(res.manifest, indent=2)
    res.files, res.entry, res.requirements, res.cogs = files, entry, sorted(reqs), []
    res.warnings.append("Standalone module: live hot-reload is unavailable — Live Sync pushes files, then restart.")
    return res
