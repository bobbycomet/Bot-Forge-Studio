"""Builds the web dashboard (``dashboard/``) from a graph.

The bot stays discord.py (see :mod:`project`). This adds a discord.js/Express app next to it:

    dashboard/server.js  bs_dash.js  config.json  package.json  routes/*.js  web/public/*

``config.json`` is the *translation* of the bot: pages for its commands, counters, tables and modules.
Everything except server.js / bs_dash.js / package.json reloads live (the dashboard re-reads config.json
and routes/ when they change), so Live Sync updates a running dashboard without a restart.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

from .. import __version__
from . import jscheck
from .codegen import GenError
from .codegen_js import compile_web_component
from .model import Graph, Node
from .nodes_web import DASH_ENV, DISCORDJS, EXPRESS, NS, WS, finish_pages, parse_pages
from . import web_validate
from .web_assets import APP_JS, INDEX_HTML, LIVE_JS, STYLE_CSS

RUNTIME_DIR = Path(__file__).resolve().parent.parent / "runtime"
SERVER_SRC = RUNTIME_DIR / "dash_server.js"
HELPERS_SRC = RUNTIME_DIR / "bs_dash.js"
MOCK_SRC = RUNTIME_DIR / "dash_mock.js"
NODE_ENGINE = ">=22.13"
GUILD_KEY = re.compile(r"^\s*\{(?:guild\.id|guild_id)\}\s*:")   # keys shaped "serverId:something"


def split_package(spec: str) -> tuple[str, str]:
    """'pkg@^1.2' -> ('pkg', '^1.2');  '@scope/pkg@1' -> ('@scope/pkg', '1');  'pkg' -> ('pkg', '*')."""
    spec = spec.strip()
    i = spec.rfind("@")
    if i > 0:
        return spec[:i], spec[i + 1:] or "*"
    return spec, "*"


def package_json(name: str, packages) -> str:
    deps: dict[str, str] = {}
    for spec in packages:
        pkg, ver = split_package(spec)
        if pkg and re.fullmatch(r"(@[a-z0-9._~-]+/)?[a-z0-9._~-]+", pkg):
            deps[pkg] = ver
    pj = {"name": name, "version": "1.0.0", "private": True, "description": "Web dashboard generated by Bot Forge Studio",
          "main": "server.js", "scripts": {"start": "node server.js"}, "engines": {"node": NODE_ENGINE},
          "dependencies": dict(sorted(deps.items()))}
    return json.dumps(pj, indent=2) + "\n"


def _literal_prop(graph: Graph, node: Node, key: str) -> str | None:
    """A property's value, or None when a wire overrides it (then it is not known at build time)."""
    if graph.incoming(node.id, key) is not None:
        return None
    v = node.prop_value(key)
    return None if v is None else str(v)


def translate_bot(graph: Graph, skip: set[str] = frozenset()) -> tuple[list[dict], list[dict]]:
    """Derive dashboard pages and the command list from the bot graph (``skip`` = node ids that live in the dashboard)."""
    pages: list[dict] = []
    commands: list[dict] = []
    for n in sorted((n for n in graph.nodes.values() if n.id not in skip), key=lambda n: (n.y, n.x)):
        if n.type_id == "trigger.slash":
            commands.append({
                "name": str(n.prop_value("name") or ""), "description": str(n.prop_value("description") or ""),
                "params": str(n.prop_value("params") or ""),
                "permission": "" if n.prop_value("require_permission") in (None, "", "none") else str(n.prop_value("require_permission")),
            })
    if commands:
        pages.append({"title": "Commands", "type": "commands", "arg": "", "scope": "guild"})
    for n in sorted((n for n in graph.nodes.values() if n.id not in skip), key=lambda n: (n.y, n.x)):
        spec = n.spec
        if spec is None:
            continue
        if spec.dash_pages is not None:
            try:
                pages += list(spec.dash_pages(n))
            except Exception:  # a plugin's bad descriptor must not break the build
                continue
        if n.type_id in ("eco.balance", "eco.give", "eco.spend", "eco.transfer", "eco.top"):
            acct = _literal_prop(graph, n, "account") or "wallet"
            if NS.match(acct):
                pages.append({"title": f"{acct}", "type": "leaderboard", "arg": acct, "scope": "guild"})
        if n.type_id in ("store.incr", "store.get", "store.set"):
            ns, key = _literal_prop(graph, n, "namespace"), _literal_prop(graph, n, "key")
            if not ns or not NS.match(ns) or key is None:
                continue
            scope = "guild" if GUILD_KEY.match(key) else "global"
            if n.type_id == "store.incr":
                pages.append({"title": f"{ns}" + ("" if scope == "guild" else " (all servers)"), "type": "leaderboard",
                              "arg": ns, "scope": scope})
            else:
                pages.append({"title": f"{ns}" + ("" if scope == "guild" else " (all servers)"), "type": "kv",
                              "arg": ns, "scope": scope, "edit": False})
    return pages, commands


def build_dashboard(graph: Graph, web_comps: list[list[Node]], res, used: set) -> dict[str, str]:
    """Compile the dashboard. Errors/warnings/env land on *res*; returns {relative path: text}."""
    s = graph.settings
    dashes = [n for c in web_comps for n in c if n.type_id == "module.dashboard"]
    if not dashes:
        res.errors.append("Web Routes and Web pages need a Web Dashboard node: it hosts the web server they run in.")
        return {}
    if len(dashes) > 1:
        res.warnings.append("There is more than one Web Dashboard node — only the first one is used.")
    dash = dashes[0]
    p = dash.prop_value

    files: dict[str, str] = {}
    requires: set[str] = {DISCORDJS, EXPRESS, WS} | set(s.extra_packages)
    for comp in web_comps:
        try:
            src = compile_web_component(graph, comp, used)
        except GenError as e:
            res.errors.append(str(e))
            continue
        if src is None:
            continue
        res.warnings += src.warnings
        requires |= src.requires
        for name, default, comment in src.env:
            res.env.setdefault(name, (default, comment))
        if src.path:
            files[src.path] = src.source
            issue = jscheck.check(src.source)
            if issue:
                res.errors.append(f"{src.path}:{issue[0] + 1}: {issue[2]}")
    for name, default, comment in DASH_ENV:
        res.env.setdefault(name, (default, comment))

    site_files, site_nav, site_cfg = build_site(graph, web_comps, res)
    files.update(site_files)
    pages: list[dict] = [{"title": "Overview", "type": "overview", "arg": "", "scope": "guild"}]
    commands: list[dict] = []
    if p("translate"):
        auto, commands = translate_bot(graph, {n.id for c in web_comps for n in c})
        pages += auto
    if p("announce"):
        pages.append({"title": "Announce", "type": "announce", "arg": "", "scope": "guild"})
    pages += site_nav
    pages += parse_pages(p("pages"))
    pages, allow = finish_pages(pages)

    accent = re.sub(r"[^0-9a-fA-F]", "", str(p("accent") or ""))[:6]
    accent = accent if len(accent) == 6 else "66c0f4"
    title = (str(p("title") or "Bot Dashboard").strip() or "Bot Dashboard")[:60]
    ids = [x for x in re.split(r"[,\s]+", str(p("restrict_user_ids") or "")) if x.isdigit()]
    cfg = {"title": title, "accent": accent, "botName": s.name, "tokenEnv": s.token_env, "pages": pages,
           "allow": allow, "commands": commands, "restrictUserIds": ids, "sitePages": site_cfg}
    files["dashboard/config.json"] = json.dumps(cfg, indent=2, ensure_ascii=False) + "\n"
    esc = title.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
    files["dashboard/web/public/index.html"] = INDEX_HTML.replace("__BS_TITLE__", esc)
    files["dashboard/web/public/style.css"] = STYLE_CSS
    files["dashboard/web/public/app.js"] = APP_JS
    files["dashboard/web/public/bs-live.js"] = LIVE_JS
    files["dashboard/server.js"] = SERVER_SRC.read_text(encoding="utf-8")
    files["dashboard/bs_dash.js"] = HELPERS_SRC.read_text(encoding="utf-8")
    files["dashboard/dash_mock.js"] = MOCK_SRC.read_text(encoding="utf-8")      # inert unless BS_TEST_MODE=1 (and then loopback-only)
    files["dashboard/package.json"] = package_json(f"{s.slug}-dashboard", sorted(requires, key=str.lower))
    return files


_SLUG = re.compile(r"[^a-z0-9]+")


def _slug(text, fallback="page") -> str:
    return _SLUG.sub("-", str(text or "").lower()).strip("-")[:40] or fallback


def _sorted(nodes):
    return sorted(nodes, key=lambda n: (n.y, n.x))


def build_site(graph: Graph, web_comps: list[list[Node]], res) -> tuple[dict[str, str], list[dict], dict]:
    """HTML Page / CSS / Browser JavaScript nodes -> dashboard/web/public/site/*.  Returns (files, menu pages, per-page config)."""
    files: dict[str, str] = {}
    nav: list[dict] = []
    cfg: dict[str, dict] = {}
    everything = [n for c in web_comps for n in c]
    pages = _sorted(n for n in everything if n.type_id == "web.html")
    used: set[str] = set()
    attached: set[str] = set()
    for page in pages:
        pv = page.prop_value
        slug = _slug(pv("slug") or pv("title"), "page")
        base, i = slug, 2
        while slug in used:
            slug, i = f"{base}-{i}", i + 1
        used.add(slug)
        title = str(pv("title") or "Page")[:80]
        html_code = str(pv("code") or "")
        for line, col, sev, msg in web_validate.check_html(html_code):
            (res.errors if sev == "error" else res.warnings).append(f"site/{slug}.html:{line + 1}: {msg}")
        links = [f'<link rel="stylesheet" href="/style.css">'] if pv("theme") else []
        scripts = ['<script src="/bs-live.js"></script>']
        feeders = _sorted(graph.nodes[e.src] for e in graph.edges
                          if e.dst == page.id and e.dst_port == "assets" and e.src in graph.nodes)
        for n in feeders:
            attached.add(n.id)
            nslug = _slug(n.prop_value("name"), n.type_id.split(".")[-1])
            code = str(n.prop_value("code") or "")
            if n.type_id == "web.css":
                fname = f"site/{slug}.{nslug}.css"
                for line, col, sev, msg in web_validate.check_css(code):
                    (res.errors if sev == "error" else res.warnings).append(f"{fname}:{line + 1}: {msg}")
                files[f"dashboard/web/public/{fname}"] = code if code.endswith("\n") else code + "\n"
                links.append(f'<link rel="stylesheet" href="/{fname}">')
            elif n.type_id == "web.js":
                fname = f"site/{slug}.{nslug}.js"
                for line, col, sev, msg in web_validate.check_browser_js(code):
                    (res.errors if sev == "error" else res.warnings).append(f"{fname}:{line + 1}: {msg}")
                files[f"dashboard/web/public/{fname}"] = code if code.endswith("\n") else code + "\n"
                scripts.append(f'<script src="/{fname}" defer></script>')
        esc = title.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
        back = '<p class="muted"><a href="/">← Dashboard</a></p>\n' if pv("back_link") else ""
        files[f"dashboard/web/public/site/{slug}.html"] = (
            f'<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n'
            f'<meta name="viewport" content="width=device-width, initial-scale=1">\n<title>{esc}</title>\n'
            + "\n".join(links) + "\n</head>\n<body>\n" + back + html_code.rstrip() + "\n"
            + "\n".join(scripts) + "\n</body>\n</html>\n")
        cfg[slug] = {"login": bool(pv("login"))}
        nt = str(pv("nav_title") or "").strip()
        if nt:
            nav.append({"title": nt[:40], "type": "site", "arg": slug, "scope": "guild"})
    for n in everything:
        if n.type_id in ("web.css", "web.js") and n.id not in attached:
            res.warnings.append(f"[{n.id}] {n.spec.title} is not connected to an HTML Page and was not published")
    return files, nav, cfg
